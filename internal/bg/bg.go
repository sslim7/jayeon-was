// Package bg 는 응답을 보낸 뒤 도는 백그라운드 고루틴의 안전장치를 모은다.
//
// **왜 별도 패키지인가** — 이 안전장치를 쓰는 곳이 도메인 전반에 걸쳐 있어, 어느 한
// 도메인 패키지에 두면 나머지가 그 도메인을 import 하게 된다.
// internal/httpx 는 HTTP 응답을 만드는 유틸이라 요청이 끝난 뒤의 일과는 성격이 다르다.
// 그래서 의존이 한 방향으로만 흐르는 잎(leaf) 패키지를 따로 뒀다 — 여기는 아무것도 import 하지 않는다.
package bg

import (
	"log"
	"runtime/debug"
)

// Recover 는 고루틴의 panic 을 잡아 로그로 남긴다. **고루틴 첫 줄에 defer 로 건다.**
//
//	go func() {
//		defer bg.Recover("admin: 감사 로그 기록")
//		...
//	}()
//
// Go 에서 고루틴의 panic 은 프로세스 전체를 죽인다. 응답이 이미 나간 요청은 무사하지만,
// 그 순간 같은 인스턴스에서 처리 중이던 **다른 사용자의 요청이 전부 끊긴다.**
// 백그라운드 작업은 어느 것도 그만한 값어치가 없다 — 그 작업 하나만 실패하고 끝나야 한다.
//
// 조용히 삼키면 원인을 영영 못 찾으므로 panic 값과 스택 트레이스를 함께 남긴다.
// 스택은 지금이 아니면 사라진다 — 이 함수가 반환하는 순간 프레임이 풀린다.
//
// **label 에 전화번호·문구·인증번호처럼 남기면 안 되는 값을 넣지 마라.**
// 어느 작업이었는지만 알면 되므로 호출부의 고정 문자열로 충분하다.
// 이 함수는 호출부 변수를 스스로 들여다보지 않으며, panic 값과 스택 외에는 아무것도 남기지 않는다.
//
// recover 는 defer 된 함수가 **직접** 호출해야 동작한다. 그래서 이 함수를 그대로
// `defer bg.Recover(...)` 로 걸어야 하고, `defer func() { bg.Recover(...) }()` 로 감싸면 잡지 못한다.
func Recover(label string) {
	r := recover()
	if r == nil {
		return
	}
	// 스택에는 panic 지점까지의 프레임이 그대로 들어 있다 — 아직 풀리지 않았기 때문이다.
	log.Printf("[ERROR] %s: 백그라운드 작업이 panic 했다: %v\n%s", label, r, debug.Stack())
}
